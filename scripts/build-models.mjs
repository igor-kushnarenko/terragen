import { writeFile, mkdir } from 'node:fs/promises';
import { tsImport } from 'tsx/esm/api';
import { GLTFExporter } from 'three/addons/exporters/GLTFExporter.js';
const { BUILTIN_INFO, makeBuiltinModel } = await tsImport('../src/model-shapes.ts', import.meta.url);
globalThis.FileReader = class {
    async readAsArrayBuffer(blob) { this.result = await blob.arrayBuffer(); this.onloadend?.(); }
    async readAsDataURL(blob) { this.result = `data:${blob.type};base64,${Buffer.from(await blob.arrayBuffer()).toString('base64')}`; this.onloadend?.(); }
};
await mkdir('public/models', { recursive: true });
const pack = {};
for (const id of Object.keys(BUILTIN_INFO)) {
    const result = await new GLTFExporter().parseAsync(makeBuiltinModel(id), { binary: true });
    const bytes = Buffer.from(result); await writeFile(`public/models/${id}.glb`, bytes); pack[id] = bytes.toString('base64');
}
await writeFile('src/builtin-models.ts', '// Generated by scripts/build-models.mjs. Authored local models.\nexport const BUILTIN_GLB: Record<string, string> = ' + JSON.stringify(pack) + ';\n');
await writeFile('public/models/LICENSE.txt', 'These models were authored for GenTerrain. No third-party assets or network resources are used.\n');
console.log('Built local GLB library: ' + Object.keys(pack).length + ' models');
